const PixelGlyph* findGlyph(char ch) {
  for (const PixelGlyph& g : kPixelGlyphs) {
    if (g.ch == ch) return &g;
  }
  return nullptr;
}

// Width of the label in the pixel font, -1 if a character is missing.
int pixelTextWidth(const std::string& label) {
  int w = 0;
  for (size_t i = 0; i < label.size(); i++) {
    const PixelGlyph* g = findGlyph(label[i]);
    if (g == nullptr) return -1;
    w += g->width + (i > 0 ? kGlyphGap : 0);
  }
  return w;
}

const ui::Font& fallbackFont() { return ui::fonts::kRobotoCondensedBold15; }

// Frame thickness and padding: 2 + 2 px, 1 + 1 px if the name would not fit
// into kLineIconWidth otherwise.
int frameBorder(int text_width) {
  return text_width + 2 * (2 + 2) > kLineIconWidth ? 1 : 2;
}

int frameWidth(int text_width) {
  return std::max(kLineIconWidth, text_width + 4 * frameBorder(text_width));
}

