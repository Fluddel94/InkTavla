"""Embeds the settings page (web/) into the firmware.

Inlines web/style.css and web/app.js into web/index.html, compresses the
result with gzip and writes it as a C array to src/generated/settings_page.h
(not in the repository; written before every build of the device, so the
page always matches the firmware).

Runs as a PlatformIO pre-build script (extra_scripts in platformio.ini) and
also on its own:

    python tools/embed_web.py

Uses the Python standard library only. The output only changes when the
page changes (gzip without a time stamp), so the firmware is not rebuilt
needlessly.
"""

import gzip
import io
import os
import re
import sys


def build(project_dir):
    web = os.path.join(project_dir, "web")
    with open(os.path.join(web, "index.html"), encoding="utf-8") as f:
        html = f.read()
    with open(os.path.join(web, "style.css"), encoding="utf-8") as f:
        css = f.read()
    with open(os.path.join(web, "app.js"), encoding="utf-8") as f:
        js = f.read()

    link = '<link rel="stylesheet" href="style.css">'
    script = '<script src="app.js"></script>'
    if link not in html or script not in html:
        raise SystemExit("embed_web.py: web/index.html must reference style.css and app.js")
    # The browser ends an inline block at the first closing tag, in any case.
    if re.search(r"</script", js, re.IGNORECASE):
        raise SystemExit("embed_web.py: app.js must not contain </script")
    if re.search(r"</style", css, re.IGNORECASE):
        raise SystemExit("embed_web.py: style.css must not contain </style")
    html = html.replace(link, "<style>\n" + css + "</style>")
    html = html.replace(script, "<script>\n" + js + "</script>")

    buffer = io.BytesIO()
    with gzip.GzipFile(fileobj=buffer, mode="wb", compresslevel=9, mtime=0) as gz:
        gz.write(html.encode("utf-8"))
    data = buffer.getvalue()

    lines = [
        "// Generated by tools/embed_web.py from web/ - do not edit.",
        "#pragma once",
        "",
        "#include <cstdint>",
        "",
        "// The settings page (index.html with style.css and app.js inlined), gzip.",
        "inline constexpr uint8_t kSettingsPageGz[] = {",
    ]
    for i in range(0, len(data), 16):
        lines.append("    " + ", ".join("0x%02x" % b for b in data[i:i + 16]) + ",")
    lines += ["};", ""]
    text = "\n".join(lines)

    out_dir = os.path.join(project_dir, "src", "generated")
    out = os.path.join(out_dir, "settings_page.h")
    os.makedirs(out_dir, exist_ok=True)
    old = None
    if os.path.exists(out):
        with open(out, encoding="utf-8") as f:
            old = f.read()
    if old != text:
        with open(out, "w", encoding="utf-8", newline="\n") as f:
            f.write(text)
    print("embed_web.py: settings page %d bytes, %d bytes gzip" % (len(html.encode()), len(data)))


try:
    Import("env")  # noqa: F821 (PlatformIO / SCons)
    build(env.subst("$PROJECT_DIR"))  # noqa: F821
except NameError:
    if __name__ == "__main__":
        build(os.path.dirname(os.path.dirname(os.path.abspath(sys.argv[0]))))
